// Problem Summary: Find the minimum length of a subarray that appears only once in the given array.
// Problem Link: https://leetcode.com/problems/smallest-unique-subarray/
//
// Approach:
// The problem asks for the smallest length `L` such that there exists at least one subarray of length `L` that appears only once in the input array `nums`.
// We can use binary search on the possible lengths of the subarray. The minimum possible length is 1 and the maximum is `nums.length`.
// For a given length `L` in the binary search, we need to check if there's any unique subarray of that length.
// To efficiently check for unique subarrays of a fixed length `L`, we can use rolling hashes.
// For a given length `L`, we iterate through all possible subarrays of length `L`.
// For each subarray, we calculate its hash value. We can maintain a map (or frequency array if element values are constrained and small enough, but here they can be large) to store the count of each hash value encountered.
// If any hash value appears only once, it means there's a potentially unique subarray of length `L`.
// However, hash collisions can occur. To handle this, we can either use a good polynomial rolling hash function with a large prime modulus and a suitable base, or we can store the actual subarray (or its starting index) along with the hash to verify uniqueness in case of a hash collision. A simpler approach for this problem, given the constraints and the nature of finding the *minimum* length, is to use a robust rolling hash and accept a small probability of error, or to be more thorough by storing counts of actual subarray representations if hash collisions become a concern.
// For this solution, we'll use polynomial rolling hash. We'll use two different hash functions (different bases and moduli) to significantly reduce the chance of collisions. A subarray is considered unique if both of its hash values appear only once.
//
// The `check(length)` function will:
// 1. Initialize two hash maps, `hash1Counts` and `hash2Counts`, to store the frequencies of hash values generated by two different hash functions.
// 2. Initialize two sets, `hash1Seen` and `hash2Seen`, to keep track of hash values encountered so far for the current length. This is more efficient than iterating through the map values.
// 3. Calculate the initial hash values for the first subarray of `length`.
// 4. Iterate through the rest of the array, updating the rolling hashes for each subsequent subarray of `length`.
// 5. For each hash pair, update their counts in `hash1Counts` and `hash2Counts`.
// 6. After processing all subarrays of `length`, iterate through the generated hash values. If any hash pair has a count of 1 in both maps, then a unique subarray of `length` exists.
//
// Binary Search:
// - `low = 1`, `high = nums.length`
// - While `low <= high`:
//     - `mid = low + (high - low) / 2`
//     - If `check(mid)` returns true (meaning a unique subarray of length `mid` exists):
//         - This `mid` is a potential answer. We try to find a smaller length, so `ans = mid`, `high = mid - 1`.
//     - Else (`check(mid)` returns false):
//         - We need a larger length, so `low = mid + 1`.
//
// Rolling Hash Implementation:
// We use two hash functions to minimize collisions.
// Hash function 1: `h1 = (h1 * base1 + nums[i]) % mod1`
// Hash function 2: `h2 = (h2 * base2 + nums[i]) % mod2`
//
// To efficiently calculate rolling hashes:
// When sliding the window from `[i, i + length - 1]` to `[i + 1, i + length]`:
// `new_hash = (old_hash - nums[i] * power) * base + nums[i + length]`
// We need to precompute powers of the bases modulo the moduli.
// `power = base^(length-1) % mod`
// The subtraction `old_hash - nums[i] * power` can result in a negative number, so we need to handle modular arithmetic carefully: `(old_hash - (nums[i] * power) % mod + mod) % mod`.
//
// Time Complexity:
// The binary search performs `O(log N)` iterations, where N is `nums.length`.
// Inside the `check(length)` function, calculating rolling hashes for all subarrays of length `L` takes `O(N)` time. Map operations (insertion and lookup) take `O(1)` on average for hash maps.
// Thus, the total time complexity is `O(N * log N)`.
//
// Space Complexity:
// For the `check(length)` function, we use hash maps to store counts of hash values. In the worst case, all subarrays of a given length could have distinct hash values.
// The number of subarrays of length `L` is `N - L + 1`.
// Therefore, the space complexity for the hash maps can be up to `O(N)`.
// The overall space complexity is `O(N)`.

import java.util.HashMap;
import java.util.Map;

class Solution {

    // Moduli and bases for two hash functions to minimize collisions.
    private static final long MOD1 = 1_000_000_007;
    private static final long BASE1 = 31; // A prime base
    private static final long MOD2 = 1_000_000_009;
    private static final long BASE2 = 37; // Another prime base

    private int[] nums;
    private int n;

    // This method checks if there exists any unique subarray of a given length.
    // It uses rolling hashes to efficiently compute hashes for all subarrays of that length.
    private boolean check(int length) {
        if (length == 0) return false; // Length 0 is not valid.

        // Hash maps to store the frequency of each hash pair encountered.
        // Key: A combined hash value (e.g., hash1 * MOD2 + hash2) or we can use nested maps.
        // Here, we use two separate maps for clarity and efficiency.
        Map<Long, Integer> hash1Counts = new HashMap<>();
        Map<Long, Integer> hash2Counts = new HashMap<>();

        // Precompute powers of bases modulo moduli.
        // power1 = BASE1^(length-1) % MOD1
        // power2 = BASE2^(length-1) % MOD2
        long power1 = 1;
        long power2 = 1;
        for (int i = 0; i < length - 1; i++) {
            power1 = (power1 * BASE1) % MOD1;
            power2 = (power2 * BASE2) % MOD2;
        }

        // Calculate initial hash for the first subarray of 'length'.
        long currentHash1 = 0;
        long currentHash2 = 0;
        for (int i = 0; i < length; i++) {
            currentHash1 = (currentHash1 * BASE1 + nums[i]) % MOD1;
            currentHash2 = (currentHash2 * BASE2 + nums[i]) % MOD2;
        }

        // Store the counts of the first hash pair.
        hash1Counts.put(currentHash1, hash1Counts.getOrDefault(currentHash1, 0) + 1);
        hash2Counts.put(currentHash2, hash2Counts.getOrDefault(currentHash2, 0) + 1);

        // Slide the window and update rolling hashes.
        for (int i = 1; i <= n - length; i++) {
            // Remove the contribution of the leftmost element.
            // (currentHash1 - nums[i-1] * power1) % MOD1
            // Need to handle potential negative results from subtraction.
            currentHash1 = (currentHash1 - (nums[i - 1] * power1) % MOD1 + MOD1) % MOD1;
            currentHash1 = (currentHash1 * BASE1 + nums[i + length - 1]) % MOD1;

            currentHash2 = (currentHash2 - (nums[i - 1] * power2) % MOD2 + MOD2) % MOD2;
            currentHash2 = (currentHash2 * BASE2 + nums[i + length - 1]) % MOD2;

            // Store the counts of the current hash pair.
            hash1Counts.put(currentHash1, hash1Counts.getOrDefault(currentHash1, 0) + 1);
            hash2Counts.put(currentHash2, hash2Counts.getOrDefault(currentHash2, 0) + 1);
        }

        // After processing all subarrays, check if any hash pair has a count of 1 in both maps.
        // This indicates a unique subarray.
        // Iterate through one of the hash maps. If a hash value has a count of 1,
        // check if its corresponding hash from the other hash function also has a count of 1.
        for (Map.Entry<Long, Integer> entry : hash1Counts.entrySet()) {
            long h1 = entry.getKey();
            int count1 = entry.getValue();

            // If hash1 appears only once
            if (count1 == 1) {
                // We need to find the corresponding hash2 value.
                // This requires a way to map hash1 to hash2.
                // A simpler approach is to iterate through all potential hash2 values,
                // but this is inefficient if hash2 has many distinct values.
                //
                // A better approach for this problem structure:
                // We need to find a subarray whose hash pair (h1, h2) appears only once.
                // The current `check` function counts frequencies of individual hashes.
                // To correctly check for unique *pairs*, we should count pairs directly.
                //
                // Let's rethink the counting to pair hashes.
                // We can use a map where the key is a custom object or a combined long hash
                // representing the pair (hash1, hash2).

                // --- Revised approach to count unique hash pairs ---
                // Let's re-implement the `check` function to count pairs directly.
                // This is more robust.
                return checkWithPairCounting(length);
            }
        }

        // If no unique subarray found with the current `check` method logic.
        // This part of the code is effectively superseded by the call to `checkWithPairCounting`.
        return false;
    }


    // Revised `check` function that counts frequency of hash PAIRS.
    private boolean checkWithPairCounting(int length) {
        if (length == 0) return false;

        // Use a map to store counts of unique hash pairs.
        // Key: combined hash (e.g., hash1 * MOD2 + hash2) or a string representation.
        // For simplicity and performance, we can combine them if the moduli are large enough.
        // A safer way is to use a nested map or a custom Pair class.
        // Let's use a map where the key is the first hash and the value is another map
        // storing counts of the second hash for that first hash.
        // `Map<Long, Map<Long, Integer>> pairCounts` where outer key is hash1, inner key is hash2.
        Map<Long, Map<Long, Integer>> pairCounts = new HashMap<>();

        long power1 = 1;
        long power2 = 1;
        for (int i = 0; i < length - 1; i++) {
            power1 = (power1 * BASE1) % MOD1;
            power2 = (power2 * BASE2) % MOD2;
        }

        long currentHash1 = 0;
        long currentHash2 = 0;
        for (int i = 0; i < length; i++) {
            currentHash1 = (currentHash1 * BASE1 + nums[i]) % MOD1;
            currentHash2 = (currentHash2 * BASE2 + nums[i]) % MOD2;
        }

        // Add the first pair
        pairCounts.computeIfAbsent(currentHash1, k -> new HashMap<>())
                  .put(currentHash2, pairCounts.get(currentHash1).getOrDefault(currentHash2, 0) + 1);

        for (int i = 1; i <= n - length; i++) {
            currentHash1 = (currentHash1 - (nums[i - 1] * power1) % MOD1 + MOD1) % MOD1;
            currentHash1 = (currentHash1 * BASE1 + nums[i + length - 1]) % MOD1;

            currentHash2 = (currentHash2 - (nums[i - 1] * power2) % MOD2 + MOD2) % MOD2;
            currentHash2 = (currentHash2 * BASE2 + nums[i + length - 1]) % MOD2;

            // Add the current pair
            pairCounts.computeIfAbsent(currentHash1, k -> new HashMap<>())
                      .put(currentHash2, pairCounts.get(currentHash1).getOrDefault(currentHash2, 0) + 1);
        }

        // Check if any pair has a count of 1.
        for (Map<Long, Integer> innerMap : pairCounts.values()) {
            for (int count : innerMap.values()) {
                if (count == 1) {
                    return true; // Found a unique subarray of this length.
                }
            }
        }

        return false; // No unique subarray of this length found.
    }


    // Main method to find the smallest unique subarray length.
    // Uses binary search on the possible lengths.
    public int smallestUniqueSubarray(int[] nums) {
        this.nums = nums;
        this.n = nums.length;

        // Binary search for the smallest length `L` such that `check(L)` is true.
        int low = 1;
        int high = n;
        int ans = n; // Initialize with the maximum possible length.

        while (low <= high) {
            int mid = low + (high - low) / 2; // Current length to check.

            // If there's a unique subarray of length `mid`, it's a potential answer.
            // We try to find an even smaller length.
            if (checkWithPairCounting(mid)) { // Using the revised checker
                ans = mid;
                high = mid - 1;
            } else {
                // If no unique subarray of length `mid` exists, we need a larger length.
                low = mid + 1;
            }
        }

        return ans;
    }

    // Example usage:
    // public static void main(String[] args) {
    //     Solution sol = new Solution();
    //     System.out.println(sol.smallestUniqueSubarray(new int[]{3, 3, 3})); // Output: 3
    //     System.out.println(sol.smallestUniqueSubarray(new int[]{2, 1, 2, 3, 3})); // Output: 1
    //     System.out.println(sol.smallestUniqueSubarray(new int[]{1, 1, 2, 2, 1})); // Output: 2
    // }
}
